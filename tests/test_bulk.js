const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const b=require('../functions/bulk-content');
const root=path.join(__dirname,'..');
const sample=JSON.parse(fs.readFileSync(path.join(root,'templates/ESEMPIO_PACCHETTO_IA.json'),'utf8'));
const out=b.normalize(sample);
assert.equal(out.errors.length,0,JSON.stringify(out.errors));
assert.equal(out.questions.length,5);
assert.equal(out.activities.length,2);
assert.equal(out.questions[1].payload.correct,1);
assert.equal(out.questions[3].payload.correct,1);
assert.equal(out.questions[4].payload.pairs.length,4);
const csv=fs.readFileSync(path.join(root,'templates/DOMANDE_EXCEL_CSV.csv'),'utf8');
const fromCsv=b.parse(csv,'example.csv');
assert.deepEqual(fromCsv.errors,[]);
assert.equal(fromCsv.questions.length,5);
assert.equal(fromCsv.questions.find(q=>q.type==='match').payload.pairs.length,3);
assert.equal(b.normalize({version:1,questions:[sample.questions[0],sample.questions[0]]}).warnings.length,1);
assert.equal(b.normalize({version:1,questions:[{type:'mcq',prompt:'Bad',topic:'T',options:['a','b'],answer:'c'}]}).errors.length,1);
assert.equal(b.normalize({version:1,questions:[{type:'swipe',prompt:'Bad',topic:'T',correct:'maybe'}]}).errors.length,1);
assert.equal(b.normalize({version:1,questions:[{type:'error',prompt:'Bad',topic:'T',chunks:['a','b'],wrong_index:3}]}).errors.length,1);
assert.equal(b.normalize({version:1,questions:[{type:'match',prompt:'Bad',topic:'T',pairs:[['a','b'],['a','c']]}]}).errors.length,1);
assert.throws(()=>b.parseCSV('some;other\na;b'),/colonne obbligatorie/);
const many=Array.from({length:121},(_,i)=>({...sample.questions[0],prompt:'P '+i}));
assert.throws(()=>b.normalize({version:1,questions:many}),/Limite/);
console.log('OK: 12 verifiche formato/importatore');

const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {webcrypto}=require('node:crypto');
const root=path.join(__dirname,'..'),b=require('../functions/bulk-content');
const sample=fs.readFileSync(path.join(root,'templates/DOMANDE_FACILI_PER_DOCENTE.txt'),'utf8');
const lesson=b.parse(sample,'lesson.txt');
assert.equal(lesson.errors.length,0,lesson.errors.join('\n'));
assert.equal(lesson.questions.length,6);
assert.deepEqual(lesson.questions.map(q=>q.type),['swipe','mcq','fill','match','listen_mcq','spell']);
assert.equal(lesson.questions[0].payload.correct,true);
assert.equal(lesson.questions[1].payload.correct,0);
assert.equal(lesson.questions[3].payload.pairs.length,3);
assert.equal(lesson.activities.length,2);
assert.equal(lesson.activities[0].game_type,'memory');
assert.equal(lesson.activities[1].time_attack,true);
assert.equal(lesson.questions[4].payload.options.length,3);
assert.deepEqual(lesson.questions[5].payload.answers,['elephant']);
const invalid=b.parse('ARGOMENTO: T\nGIOCO: Inventato\nDOMANDA: Q\nRISPOSTA: a','any.txt');
assert.equal(invalid.errors.length,1);
assert.equal(b.parse('ARGOMENTO: T\nGIOCO: Vero o falso\nDOMANDA: The cats sleeps.\nRISPOSTA: falso','any.txt').questions[0].payload.correct,false);
const server=fs.readFileSync(path.join(root,'functions/index.js'),'utf8');
assert.ok(server.includes("credentialVault"));
assert.ok(server.includes('password-change-intent'));
assert.ok(server.includes('teacher-audio/'));
assert.ok(server.includes("['listen_mcq','spell'].includes(s.data().type)&&!s.data().audio_path"));
assert.ok(fs.readFileSync(path.join(root,'storage.rules'),'utf8').includes('allow read, write: if false'));
const ui=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
const start=ui.indexOf('// Browser-only encryption:');
const end=ui.indexOf('async function openClass(',start);
assert.ok(start>0&&end>start);
const context=vm.createContext({crypto:webcrypto,TextEncoder,TextDecoder,atob,btoa,console,api:()=>{},openModal:()=>{},closeModal:()=>{}});
vm.runInContext(ui.slice(start,end)+'\nglobalThis.vault={vaultEncrypt,vaultDecrypt};',context);
(async()=>{
 const pass='This is a sufficiently long passphrase';
 const encrypted=await context.vault.vaultEncrypt('blue-panda-24',pass);
 assert.equal(encrypted.alg,'AES-GCM-PBKDF2-v1');
 assert.ok(!JSON.stringify(encrypted).includes('blue-panda'));
 assert.equal(await context.vault.vaultDecrypt(encrypted,pass),'blue-panda-24');
 await assert.rejects(()=>context.vault.vaultDecrypt(encrypted,'Incorrect password with enough characters'),/Frase segreta/);
 console.log('OK: parser docente, Memory, Time Attack, audio privato e cifratura credenziali (17 controlli + round-trip AES-GCM)');
})().catch(err=>{console.error(err);process.exitCode=1});

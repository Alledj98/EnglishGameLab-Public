'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const app=read('public/app.js');
const fn=read('functions/index.js');
const boot=read('public/bootstrap.html');
const ci=read('.github/workflows/ci.yml');
assert.ok(fn.includes('EGL_BOOTSTRAP_TEACHER_EMAIL'));
assert.ok(fn.includes("if(!TEACHER_EMAIL) return res.status(503)"));
assert.ok(boot.includes('teacherEmail'));
assert.ok(!boot.includes("signInWithEmailAndPassword('"));
assert.ok(!fs.existsSync(path.join(root,'public/firebase-config.js')));
assert.ok(!fs.existsSync(path.join(root,'.firebaserc')));
assert.ok(read('public/firebase-config.example.js').includes('YOUR_PUBLIC_WEB_API_KEY'));
assert.ok(!ci.includes('action-hosting-deploy'));
assert.ok(!/TEACHER_EMAIL\s*=\s*['"`]/.test(fn));
assert.ok(!/english-game-lab\.firebaseapp\.com/i.test(app+fn+boot));
console.log('OK: sample config isolated; teacher bootstrap fail-closed; no deploy action');
